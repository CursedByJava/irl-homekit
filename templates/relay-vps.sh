#!/bin/bash
# IRL Homekit relay: turns a free cloud VM (Oracle Cloud Always Free, Ubuntu) into the public address your phone
# streams to, so your home router needs no port forwarding. The IRL Homekit PC connects OUT to this VM over
# WireGuard and the VM passes the phone's streams (and, if set up, the remote dashboard) down that tunnel.
#
# How to use it (docs/RELAY.md has the step by step):
#   - Best: paste this whole file into "Initialization script" (cloud-init) when you create the VM.
#   - Or, on a VM that already exists:  sudo bash relay-vps.sh
# Running it again is safe: it keeps the same settings and restarts the relay.
#
# Generated by IRL Homekit {{VERSION}}. It contains your relay password (the token): keep it private.
set -euo pipefail

TOKEN="{{RELAY_TOKEN}}"
WG_PORT=51820
VM_IP=10.66.66.1      # the VM's end of the tunnel
PC_IP=10.66.66.2      # the IRL Homekit PC's end
# Ports the phone uses, passed straight through to the PC. 80/443 (remote dashboard) go through HAProxy below.
UDP_PORTS="5000,8890"
TCP_PORTS="1935"

log() { echo "[irl-homekit-relay] $*"; }
[ "$(id -u)" -eq 0 ] || { echo "Run as root: sudo bash $0"; exit 1; }

# 1. WireGuard (the tunnel) and HAProxy (the remote dashboard), from Ubuntu's own packages.
log "installing WireGuard and HAProxy"
export DEBIAN_FRONTEND=noninteractive
for i in 1 2 3 4 5; do
  apt-get update -q && apt-get install -y -q wireguard-tools haproxy openssl iptables && break
  log "install failed (cloud-init may still be updating the VM), retrying in 20 s"; sleep 20
done
command -v wg >/dev/null && command -v haproxy >/dev/null || { echo "Couldn't install WireGuard / HAProxy."; exit 1; }

# 2. Tunnel keys. Both ends work them out from the relay password, so nothing else needs copying between them.
key() { printf '%s' "$1:$TOKEN" | openssl dgst -sha256 -binary | base64; }
VM_KEY="$(key irlhk-relay-vm)"
PC_PUB="$(key irlhk-relay-pc | wg pubkey)"
PUB_IF="$(ip -4 route show default | awk '{print $5; exit}')"
[ -n "$PUB_IF" ] || { echo "No default network interface found."; exit 1; }

# 3. The tunnel, plus the forwarding rules. They live in PostUp/PostDown, so they come back with the tunnel at every
#    boot, ahead of the VM's own firewall (Oracle's Ubuntu images reject everything but SSH by default).
#    Phone streams are passed to the PC as coming from this VM (MASQUERADE), so the PC's replies go back the same way.
mkdir -p /etc/wireguard /etc/irlhk-relay
RULES="-t nat -A PREROUTING -i ${PUB_IF} -p udp -m multiport --dports ${UDP_PORTS} -j DNAT --to-destination ${PC_IP}
-t nat -A PREROUTING -i ${PUB_IF} -p tcp -m multiport --dports ${TCP_PORTS} -j DNAT --to-destination ${PC_IP}
-t nat -A POSTROUTING -o %i -j MASQUERADE
-I FORWARD 1 -i %i -j ACCEPT
-I FORWARD 1 -o %i -j ACCEPT
-I INPUT 1 -p udp --dport ${WG_PORT} -j ACCEPT
-I INPUT 1 -i %i -p icmp -j ACCEPT
-I INPUT 1 -p tcp -m multiport --dports 80,443 -j ACCEPT"
up=""; down=""
while IFS= read -r r; do
  r="$(echo " $r" | sed 's/ -j / -m comment --comment irlhk-relay -j /')"
  up="${up}PostUp = iptables${r}"$'\n'
  down="${down}PostDown = iptables$(echo "$r" | sed -E 's/ -[AI] ([A-Z]+)( 1)? / -D \1 /') || true"$'\n'
done <<< "$RULES"
# Take a running tunnel down with the rules it was started with, before they change.
systemctl stop wg-quick@irlhk.service >/dev/null 2>&1 || true
umask 077
cat > /etc/wireguard/irlhk.conf <<EOF
# IRL Homekit relay tunnel. Written by the IRL Homekit relay setup script.
[Interface]
Address = ${VM_IP}/24
ListenPort = ${WG_PORT}
PrivateKey = ${VM_KEY}
PostUp = sysctl -q -w net.ipv4.ip_forward=1
${up}${down}
[Peer]
# The IRL Homekit PC
PublicKey = ${PC_PUB}
AllowedIPs = ${PC_IP}/32
EOF
umask 022

# 4. Remote dashboard: HAProxy passes 80/443 to the PC with the visitor's real address in a PROXY header (the PC's
#    web server needs it for per-visitor sign-in limits). HTTPS stays end to end: the certificate lives on the PC.
cat > /etc/irlhk-relay/haproxy.cfg <<EOF
# IRL Homekit relay: remote dashboard. Written by the IRL Homekit relay setup script.
defaults
  mode tcp
  timeout connect 5s
  timeout client 1h
  timeout server 1h
  timeout tunnel 1h
frontend http
  bind :80
  default_backend pc_http
frontend https
  bind :443
  default_backend pc_https
backend pc_http
  server pc ${PC_IP}:80 send-proxy-v2
backend pc_https
  server pc ${PC_IP}:443 send-proxy-v2
EOF
cat > /etc/systemd/system/irlhk-relay-web.service <<'EOF'
[Unit]
Description=IRL Homekit relay (remote dashboard)
After=network-online.target wg-quick@irlhk.service
Wants=network-online.target

[Service]
# No root: a throwaway user that can only open ports 80 and 443.
Type=notify
DynamicUser=yes
ExecStart=/usr/sbin/haproxy -Ws -f /etc/irlhk-relay/haproxy.cfg
ExecReload=/bin/kill -USR2 $MAINPID
Restart=always
RestartSec=3
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
EOF

# 5. Forwarding on, and bigger network buffers (video over UDP arrives in bursts).
cat > /etc/sysctl.d/90-irlhk-relay.conf <<'EOF'
net.ipv4.ip_forward = 1
net.core.rmem_max = 7500000
net.core.wmem_max = 7500000
EOF
sysctl -q --system || true

# Older versions of this relay used frp; stop it if it's there.
systemctl disable --now irlhk-relay.service >/dev/null 2>&1 || true

systemctl daemon-reload
systemctl enable wg-quick@irlhk.service irlhk-relay-web.service >/dev/null 2>&1
systemctl restart wg-quick@irlhk.service
systemctl restart irlhk-relay-web.service
sleep 2
if systemctl is-active --quiet wg-quick@irlhk.service && systemctl is-active --quiet irlhk-relay-web.service; then
  log "relay is running. In IRL Homekit Setup, enter this VM's public IP address."
else
  log "relay did not start; see: journalctl -u wg-quick@irlhk -u irlhk-relay-web -n 50"; exit 1
fi
