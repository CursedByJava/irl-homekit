#!/bin/bash
# IRL Homekit relay: turns a free cloud VM (Oracle Cloud Always Free, Ubuntu) into the public address your phone
# streams to, so your home router needs no port forwarding. The IRL Homekit PC connects OUT to this VM and the VM
# passes the phone's streams (and, if set up, the remote dashboard) down that connection.
#
# How to use it (docs/RELAY.md has screenshots-free step by step):
#   - Best: paste this whole file into "Initialization script" (cloud-init) when you create the VM.
#   - Or, on a VM that already exists:  sudo bash relay-vps.sh
# Running it again is safe: it re-installs the same version and keeps the same settings.
#
# Generated by IRL Homekit {{VERSION}}. It contains your relay password (the token): keep it private.
set -euo pipefail

FRP_VERSION="0.71.1"
FRP_SHA_AMD64="1d9875210972a5d1a62b2dc4c48df45ab0af05d3ca1b5e494a014428259df803"
FRP_SHA_ARM64="8edf590b0c396fa42f9c147121a76af83cfc2002b08f5aef0ea1008c43482019"
TOKEN="{{RELAY_TOKEN}}"
CONTROL_PORT=7000
# Ports the phone (and the dashboard) use. The IRL Homekit PC may only open these on this VM.
UDP_PORTS="5000 8890"
TCP_PORTS="1935 80 443"

log() { echo "[irl-homekit-relay] $*"; }
[ "$(id -u)" -eq 0 ] || { echo "Run as root: sudo bash $0"; exit 1; }

case "$(uname -m)" in
  x86_64)  ARCH=amd64; SHA="$FRP_SHA_AMD64" ;;
  aarch64) ARCH=arm64; SHA="$FRP_SHA_ARM64" ;;
  *) echo "Unsupported CPU: $(uname -m)"; exit 1 ;;
esac

# 1. frp server, pinned and checksum-verified (the same check the Windows installer does).
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
NAME="frp_${FRP_VERSION}_linux_${ARCH}"
log "downloading frp ${FRP_VERSION} (${ARCH})"
for i in 1 2 3 4 5; do
  curl -fsSL -o "$TMP/frp.tar.gz" "https://github.com/fatedier/frp/releases/download/v${FRP_VERSION}/${NAME}.tar.gz" && break
  log "download failed, retrying in 10 s"; sleep 10
done
echo "${SHA}  $TMP/frp.tar.gz" | sha256sum -c - >/dev/null || { echo "frp download: checksum mismatch, refused."; exit 1; }
tar -xzf "$TMP/frp.tar.gz" -C "$TMP"
install -m 0755 "$TMP/$NAME/frps" /usr/local/bin/irlhk-frps

# 2. Settings. Only IRL Homekit (with the token) can use this relay, and only for the ports above.
mkdir -p /etc/irlhk-relay
ALLOW=""
for p in $UDP_PORTS $TCP_PORTS; do ALLOW="${ALLOW}{ single = ${p} }, "; done
cat > /etc/irlhk-relay/frps.toml <<EOF
# IRL Homekit relay (frp server). Written by the IRL Homekit relay setup script.
bindAddr = "0.0.0.0"
bindPort = ${CONTROL_PORT}
quicBindPort = ${CONTROL_PORT}
auth.method = "token"
auth.token = "${TOKEN}"
transport.tls.force = true
allowPorts = [ ${ALLOW%, } ]
log.to = "console"
log.level = "info"
EOF
chmod 600 /etc/irlhk-relay/frps.toml

# 3. Runs as a locked-down service that starts at boot and restarts if it ever stops.
cat > /etc/systemd/system/irlhk-relay.service <<'EOF'
[Unit]
Description=IRL Homekit relay (frp server)
After=network-online.target
Wants=network-online.target

[Service]
# No root: a throwaway user that can only read its settings (handed over by systemd) and open the ports above.
DynamicUser=yes
LoadCredential=frps.toml:/etc/irlhk-relay/frps.toml
ExecStart=/usr/local/bin/irlhk-frps -c ${CREDENTIALS_DIRECTORY}/frps.toml
Restart=always
RestartSec=3
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF

# 4. The VM's own firewall. Oracle's Ubuntu images reject everything but SSH by default.
open_port() { # proto port
  if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
    ufw allow "$2/$1" >/dev/null
  elif command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
    firewall-cmd --permanent --add-port="$2/$1" >/dev/null
  elif command -v iptables >/dev/null 2>&1; then
    iptables -C INPUT -p "$1" --dport "$2" -m comment --comment irlhk-relay -j ACCEPT 2>/dev/null ||
      iptables -I INPUT 1 -p "$1" --dport "$2" -m comment --comment irlhk-relay -j ACCEPT
  fi
}
for p in $UDP_PORTS $CONTROL_PORT; do open_port udp "$p"; done
for p in $TCP_PORTS $CONTROL_PORT; do open_port tcp "$p"; done
command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1 && firewall-cmd --reload >/dev/null || true
if command -v netfilter-persistent >/dev/null 2>&1; then netfilter-persistent save >/dev/null 2>&1 || true
elif [ -d /etc/iptables ]; then iptables-save > /etc/iptables/rules.v4; fi

# 5. Bigger network buffers: video over UDP arrives in bursts.
cat > /etc/sysctl.d/90-irlhk-relay.conf <<'EOF'
net.core.rmem_max = 7500000
net.core.wmem_max = 7500000
EOF
sysctl -q --system || true

systemctl daemon-reload
systemctl enable --now irlhk-relay.service
systemctl restart irlhk-relay.service
sleep 2
if systemctl is-active --quiet irlhk-relay.service; then
  log "relay is running. In IRL Homekit Setup, enter this VM's public IP address."
else
  log "relay did not start; see: journalctl -u irlhk-relay -n 50"; exit 1
fi
